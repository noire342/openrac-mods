"""Generate/check PAL bindings and audited table metadata, without game assets."""
import argparse
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
FIELDS = ('enter', 'exit', 'reset', 'state', 'motion', 'transitions', 'hit', 'capsule', 'vehicle', 'terrain')
TABLE = 'games/rac1/config/overlays/functions.tsv'


def render(checkout):
    config = json.loads((ROOT / 'compatibility.json').read_text(encoding='utf-8'))
    commit = config['openrac_commit']
    raw = subprocess.check_output(['git', '-C', str(checkout), 'show', f'{commit}:{TABLE}'])
    rows = {r[0]: r for line in raw.decode().splitlines() if not line.startswith('#')
            and len(r := line.split('\t')) >= 6}
    columns = []
    for field in FIELDS:
        addresses = {}
        for name in config['native_groups'][field]:
            for pair in rows[name][5].split(','):
                level, address = pair.split(':')
                level = int(level)
                if level in addresses:
                    raise ValueError(f'Ambiguous {field} for level {level}')
                addresses[level] = int(address, 16)
        if set(addresses) != set(range(19)):
            raise ValueError(f'{field} does not cover all 19 PAL overlays')
        columns.append(addresses)
    preamble = ('// SPDX-License-Identifier: GPL-3.0-or-later\n'
                '// Generated by tools/generate_native_addresses.py; do not edit.\n'
                f'// PAL OpenRAC {commit}; compatibility.json\n'
                '#pragma once\n#include <array>\n#include <cstdint>\nnamespace clank {\n')
    entries = '\n'.join('    {' + ', '.join(f'0x{c[level]:08X}u' for c in columns) +
                        f'}}, // {level:02d}' for level in range(19))
    addresses = (preamble + 'struct NativeAddresses { std::uint32_t ' + ', '.join(FIELDS) + '; };\n'
                 'inline constexpr std::array<NativeAddresses, 19> native_addresses{{\n' + entries + '\n}};\n}\n')
    tables = []
    for t in config['native_tables']:
        if len(t['addresses']) != 19 or len(t['sha256']) != 64:
            raise ValueError('Invalid audited native table metadata')
        values = ','.join(f'0x{int(a,16):08X}u' for a in t['addresses'])
        tables.append('    {' + f'{t["canonical"]}u,{t["size"]},"{t["sha256"]}",' + '{' + values + '}},')
    native_tables = (preamble + 'struct NativeTable {std::uint32_t canonical,size;const char* digest;std::array<std::uint32_t,19> addresses;};\n'
                     f'inline constexpr std::array<NativeTable,{len(tables)}> clank_tables{{{{\n' + '\n'.join(tables) + '\n}};\n')
    mutable_entries = []
    for t in config['mutable_regions']:
        values = ','.join(f'0x{int(a,16):08X}u' for a in t['addresses'])
        mutable_entries.append('    {' + f'{t["canonical"]}u,{t["size"]},' + '{' + values + '}},')
    native_tables += ('struct MutableRegion {std::uint32_t canonical,size;std::array<std::uint32_t,19> addresses;};\n'
                      f'inline constexpr std::array<MutableRegion,{len(mutable_entries)}> clank_mutable_regions{{{{\n' + '\n'.join(mutable_entries) + '\n}};\n}\n')
    callbacks = []
    for item in config['hud_callbacks']:
        actual = [0] * 19
        for pair in rows[item['name']][5].split(','):
            level, value = pair.split(':')
            if not actual[int(level)]:
                actual[int(level)] = int(value, 16)
        if actual != [int(v,16) for v in item['addresses']]:
            raise ValueError('HUD callback aliases differ from pinned PAL source')
        callbacks.append('    {' + f'{item["canonical"]}u,"{item["name"]}",' + '{' +
                         ','.join(f'0x{v:08X}u' for v in actual) + '}},')
    native_tables = native_tables[:-2] + ('struct HudCallback {std::uint32_t canonical;const char* name;std::array<std::uint32_t,19> addresses;};\n'
                    f'inline constexpr std::array<HudCallback,{len(callbacks)}> hud_callbacks{{{{\n' +
                    '\n'.join(callbacks) + '\n}};\n}\n')
    return {'native_addresses.hpp': addresses, 'native_tables.hpp': native_tables}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('openrac', type=pathlib.Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, output in render(args.openrac).items():
        dest = ROOT / 'src' / name
        if args.check:
            if dest.read_text(encoding='utf-8') != output:
                raise SystemExit(f'{name} differs from pinned PAL source/compatibility metadata')
        else:
            dest.write_text(output, encoding='utf-8', newline='\n')
