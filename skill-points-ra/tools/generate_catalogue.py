"""Generate an offline catalogue from an official, sanitized RA patch response."""
import hashlib
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
patch = json.loads((root/'data/3070.json').read_text(encoding='utf-8-sig'))
assert patch['ID'] == 3070 and patch['ConsoleID'] == 21
achievements = patch['Achievements']
assert len(achievements) == 178 and sum(a['Points'] for a in achievements) == 667
assert len({a['ID'] for a in achievements}) == len(achievements)
native = {}
for a in achievements:
    hits = re.findall(r'd0xH0013d4([0-9a-f]{2})=0_0xH0013d4\1=1', a['MemAddr'], re.I)
    if hits:
        index = int(hits[0], 16)-8
        if 0 <= index < 30:
            assert index not in native
            native[index] = a['ID']
# Careful Cruise additionally checks the water traversal volume; it uses a
# greater-than comparison against the prior byte instead of a 0 -> 1 pair.
careful = next(a for a in achievements if a['ID'] == 275206)
assert '0xH0013d424>d0xH0013d424' in careful['MemAddr']
native[28] = careful['ID']
assert len(native) == 30, native
def s(value):
    return json.dumps(value, ensure_ascii=True)
lines = ['// Generated by tools/generate_catalogue.py. Do not edit.', '#include "catalogue.hpp"', 'namespace skillpoints {', 'const Definition kCatalogue[] = {']
for a in achievements:
    index = next((i for i, id in native.items() if id == a['ID']), -1)
    fields = [str(a['ID']), str(a['Points']), str(index), s(a['Title']), s(a['Description']), s(a['Author']), s(a['MemAddr']), s(hashlib.sha256(a['MemAddr'].encode()).hexdigest())]
    lines.append('    {'+', '.join(fields)+'},')
lines += ['};', 'const std::size_t kCatalogueSize = sizeof(kCatalogue)/sizeof(kCatalogue[0]);', '} // namespace skillpoints', '']
(root/'src').mkdir(exist_ok=True)
(root/'src/catalogue_data.cpp').write_text('\n'.join(lines), encoding='utf-8')
manifest = {'game_id':3070, 'console_id':21, 'count':len(achievements), 'points':667,
            'source':'https://retroachievements.org/game/3070',
            'downloaded':'2026-10-28', 'native_skill_point_ids':native,
            'rules_sha256':hashlib.sha256((root/'data/3070.json').read_bytes()).hexdigest()}
(root/'data/provenance.json').write_text(json.dumps(manifest, indent=2)+'\n')
print(json.dumps({'count':len(achievements),'native_points':len(native),'new_points':len(achievements)-len(native)}))
